CREATE OR REPLACE TABLE `CURSO` (
	`id_curso` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
	`nombre_curso` VARCHAR(100),
	`num_asignaturas` INTEGER,
	PRIMARY KEY(`id_curso`)
);

