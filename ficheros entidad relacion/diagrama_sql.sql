	`provincia` VARCHAR(100),
	`beca` VARCHAR(100),
	PRIMARY KEY(`id_alumno`)
);

CREATE OR REPLACE TABLE `MATRICULA` (
	`id_alumno` VARCHAR(5) UNSIGNED NOT NULL,
	`id_asignatura` VARCHAR(5),
